import { expect, test } from '@playwright/test';
import { connectHandles, dragBy, nodeModel, shortcut } from '../helpers/drawing';
import { insertionFixture, paletteToPoint, pathPoint } from '../helpers/insertion';
import { cornerDrag, nodeGeometry } from '../helpers/resize';

test('real Pages loads P2 editor and calls Neon PostgreSQL with browser CORS', async ({ page }, testInfo) => {
  const errors: string[] = [];
  page.on('pageerror', (error) => errors.push(error.message));
  await page.goto('./');
  const faviconUrl = await page.locator('link[rel="icon"]').evaluate((element) => (element as HTMLLinkElement).href);
  expect(faviconUrl).toBe(new URL('favicon.svg', page.url()).href);
  const favicon = await page.request.get(faviconUrl);
  expect(favicon.ok()).toBe(true);
  expect(favicon.headers()['content-type']).toContain('image/svg+xml');
  await expect(page.locator('iframe')).toHaveCount(0);
  await expect(page.locator('.shape-tile')).toHaveCount(21);
  await expect(page.locator('[data-node]')).toHaveCount(6);
  await expect(page.locator('#canvasHost')).toHaveAttribute('data-ready', 'true');
  await page.screenshot({ path: testInfo.outputPath('pages-p2.png') });
  const node = nodeModel(page, 'Tiếp nhận vật tư'), id = await node.getAttribute('data-node');
  await node.dblclick();
  const input = page.getByRole('textbox', { name: 'Sửa chữ trong hình', exact: true });
  await input.fill('Vật tư P2 trực tuyến'); await input.press('Enter');
  await expect(page.getByRole('button', { name: 'Hình Vật tư P2 trực tuyến', exact: true })).toBeVisible();
  await shortcut(page, 'Control+z');
  const liveNode = page.locator(`[data-node="${id}"]`), width = await liveNode.getAttribute('data-width');
  await liveNode.click(); await dragBy(page, liveNode.locator('.react-flow__resize-control.handle.bottom.right'), 40, 25);
  await expect(liveNode).not.toHaveAttribute('data-width', width!);
  await expect(page.locator('.toast')).toHaveCount(0);
  await shortcut(page, 'Control+z'); await expect(liveNode).toHaveAttribute('data-width', width!);
  const target = nodeModel(page, 'Trả nhà cung cấp'), targetId = await target.getAttribute('data-node');
  await liveNode.hover(); await connectHandles(page, liveNode.locator('.port-right'), target.locator('.port-left'));
  const created = page.locator(`[data-edge][data-source="${id}"][data-target="${targetId}"]`);
  await expect(created).toHaveAttribute('data-kind', 'curved');
  await page.locator('.shape-tile[data-shape=arrow]').click();
  await expect(created).toHaveAttribute('data-kind', 'orthogonal');
  await shortcut(page, 'Control+z'); await expect(created).toHaveAttribute('data-kind', 'curved');
  await shortcut(page, 'Control+z'); await expect(page.locator('[data-edge]')).toHaveCount(5);
  await page.getByRole('tab', { name: 'Thuộc tính', exact: true }).click();
  await page.getByRole('button', { name: 'Hình Tiếp nhận vật tư', exact: true }).click();
  await page.getByRole('button', { name: 'Màu nền #e3f9ef', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Hình Tiếp nhận vật tư', exact: true }).locator('.node-border')).toHaveAttribute('fill', '#e3f9ef');
  await expect(page.locator('.top-status')).toHaveText('Chưa lưu · Có thay đổi');
  await page.screenshot({ path: testInfo.outputPath('pages-properties.png') });
  page.once('dialog', async (dialog) => { expect(dialog.type()).toBe('beforeunload'); await dialog.accept(); });
  await page.reload();
  await expect(page.getByRole('button', { name: 'Hình Tiếp nhận vật tư', exact: true }).locator('.node-border')).toHaveAttribute('fill', '#ffffff');
  await page.getByRole('link', { name: 'Kiểm tra nền tảng', exact: true }).click();
  await expect(page.locator('.react-flow__node')).toHaveCount(2);
  await expect(page.locator('.react-flow__edge')).toHaveCount(1);
  await page.reload();
  await expect(page.getByRole('button', { name: 'Kiểm tra API' })).toBeEnabled();
  const responsePromise = page.waitForResponse((response) => response.url().endsWith('/v1/health'));
  await page.getByRole('button', { name: 'Kiểm tra API' }).click();
  const response = await responsePromise;
  expect(response.status()).toBe(200);
  expect(response.headers()['access-control-allow-origin']).toBe('https://tux1cm.github.io');
  expect(await response.json()).toEqual({ status: 'ok', apiVersion: 'v1', database: 'ok' });
  await expect(page.getByRole('status')).toHaveText('API và PostgreSQL phản hồi OK', { timeout: 15000 });
  // Non-simple content-type forces a real browser OPTIONS preflight.
  const probe = await page.evaluate(async (url) => {
    const result = await fetch(url, { headers: { 'Content-Type': 'application/json' }, credentials: 'omit', cache: 'no-store', signal: AbortSignal.timeout(10000) });
    return { status: result.status, body: await result.json() };
  }, response.url());
  expect(probe).toEqual({ status: 200, body: { status: 'ok', apiVersion: 'v1', database: 'ok' } });
  await page.screenshot({ path: testInfo.outputPath('pages-neon-health.png') });
  await page.getByRole('link', { name: '← Về trình vẽ' }).click();
  const { host, edge, edgeId } = await insertionFixture(page);
  const point = await pathPoint(edge.locator('.react-flow__edge-path'));
  await paletteToPoint(page, 'diamond', point, true);
  await expect(host).toHaveAttribute('data-insert-edge', edgeId);
  await page.mouse.up();
  await expect(page.locator('[data-edge]')).toHaveCount(2); await expect(page.locator('[data-node]')).toHaveCount(3);
  await page.screenshot({ path: testInfo.outputPath('pages-p3-insertion.png') });
  await shortcut(page, 'Control+z'); await expect(page.locator('[data-node]')).toHaveCount(2);
  await expect(page.locator(`[data-edge="${edgeId}"]`)).toHaveCount(1);
  const source = page.locator('[data-node]').first(), x = await source.getAttribute('data-x');
  await page.keyboard.down('Control'); await dragBy(page, source, 130, 70); await page.keyboard.up('Control');
  await expect(page.locator('[data-node]')).toHaveCount(3); await expect(page.locator('[data-edge]')).toHaveCount(1);
  await expect(page.locator('[data-node]').first()).toHaveAttribute('data-x', x!);
  await page.screenshot({ path: testInfo.outputPath('pages-ctrl-drag.png') });
  await shortcut(page, 'Control+z'); await expect(page.locator('[data-node]')).toHaveCount(2);
  const ratioSource = page.locator('[data-node]').first(); await ratioSource.click();
  const beforeRatio = await nodeGeometry(ratioSource);
  await cornerDrag(page, ratioSource, 'bottom.right', 40, 8);
  const afterRatio = await nodeGeometry(ratioSource);
  expect(afterRatio.width).toBeGreaterThan(beforeRatio.width); expect(afterRatio.width / afterRatio.height).toBeCloseTo(beforeRatio.width / beforeRatio.height, 6);
  expect(afterRatio.x + afterRatio.width / 2).toBeCloseTo(beforeRatio.x + beforeRatio.width / 2, 5); expect(afterRatio.y + afterRatio.height / 2).toBeCloseTo(beforeRatio.y + beforeRatio.height / 2, 5);
  await expect(page.locator('[data-node]')).toHaveCount(2); await expect(page.locator('[data-edge]')).toHaveCount(1);
  await page.screenshot({ path: testInfo.outputPath('pages-ctrl-corner.png') });
  await shortcut(page, 'Control+z'); expect(await nodeGeometry(ratioSource)).toEqual(beforeRatio);
  expect(errors).toEqual([]);
});
